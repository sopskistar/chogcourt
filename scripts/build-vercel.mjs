import fs from 'node:fs/promises';
import {resolve} from 'node:path';
const root=resolve(import.meta.dirname,'..'),out=resolve(root,'dist');
const html=await fs.readFile(resolve(root,'index.html'),'utf8');
for(const [,script]of html.matchAll(/<script[^>]*>([\s\S]*?)<\/script>/g))new Function(script);
await fs.rm(out,{recursive:true,force:true});
await fs.mkdir(out,{recursive:true});
await fs.copyFile(resolve(root,'index.html'),resolve(out,'index.html'));
await fs.cp(resolve(root,'assets'),resolve(out,'assets'),{recursive:true});
console.log('Vercel static output prepared in dist/: frontend and artwork only. API runs in the separate PostgreSQL-backed Function.');
